export interface TypeSetting {
  readonly width: number;
  readonly cells: readonly Cell[];
}

/** Sets one line; a missing glyph is an authoring error, so it fails the build instead of dropping a letter. */
export function setType(text: string, tone: Tone): TypeSetting {
  const cells: Cell[] = [];
  let left = 0;
  for (const character of text) {
    if (character === " ") {
      left += SPACE_WIDTH;
      continue;
    }
    const glyph = glyphs[character];
    if (!glyph) throw new Error(`The pixel typeface has no glyph for "${character}".`);
    const rows = glyph.split(" ");
    for (const [row, bits] of rows.entries()) {
      for (const [column, bit] of [...bits].entries()) {
        if (bit === "1") cells.push({ column: left + column, row, tone });
      }
    }
    left += (rows[0]?.length ?? 0) + 1;
  }
  return { width: Math.max(0, left - 1), cells };
}
